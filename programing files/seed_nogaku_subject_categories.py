def load_env(env: str):
    env_file = Path(__file__).parent / (".env.dev" if env == "dev" else ".env")
    if not env_file.exists():
        print(f"ERROR: {env_file} が見つかりません", file=sys.stderr)
        sys.exit(1)
    for line in env_file.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            k, v = line.split("=", 1)
            os.environ.setdefault(k.strip(), v.strip())


async def run(dry_run: bool):
    from sqlalchemy import delete, select
    from database import AsyncSessionLocal
    from models import Subject, SubjectCreditCategory

    async with AsyncSessionLocal() as session:
        all_subjects = (await session.execute(select(Subject.id, Subject.name, Subject.credits, Subject.faculty))).all()

    by_norm: dict[str, list] = {}
    for sid, name, credits, faculty in all_subjects:
        by_norm.setdefault(_norm(name), []).append((sid, name, credits, faculty))

    def _priority(cand):
        _, _, _, faculty = cand
        return 0 if faculty in _PREFERRED_FACULTIES else 1

    unmatched: list[str] = []
    ambiguous: list[str] = []
    inserts: dict[str, dict[int, float]] = {}  # category_id -> {subject_id: credits}

    def resolve(names: list[str], cat_id: str):
        bucket = inserts.setdefault(cat_id, {})
        for nm in names:
            key = _norm(NAME_ALIASES.get(nm, nm))
            cands = by_norm.get(key)
            if not cands:
                unmatched.append(f"{cat_id}: {nm}")
                continue
            cands = sorted(cands, key=_priority)
            if len(cands) > 1 and _priority(cands[0]) == _priority(cands[1]):
                # 同優先度の候補が複数残る場合のみ要確認として記録する
                ambiguous.append(f"{cat_id}: {nm} -> {[(c[1], c[3]) for c in cands]}")
            sid, _, credits, _ = cands[0]
            bucket[sid] = float(credits) if credits is not None else 2.0

    for prefix, data in COURSES.items():
        resolve(data["kyotsu"], f"{prefix}_kyotsu")
        resolve(data["senmon"] + COMMON_SENMON, f"{prefix}_senmon_only")

    total = sum(len(v) for v in inserts.values())
    print(f"マッチ件数: {total}件 / 未マッチ: {len(unmatched)}件 / 複数候補: {len(ambiguous)}件")
    if unmatched:
        print("\n--- 未マッチ科目 ---")
        for u in unmatched:
            print(" ", u)
    if ambiguous:
        print("\n--- 複数候補（先頭を採用） ---")
        for a in ambiguous:
            print(" ", a)

    if dry_run:
        print("\n--dry-run のためDBへは書き込みません")
        return

    async with AsyncSessionLocal() as session:
        for cat_id, sub_map in inserts.items():
            await session.execute(delete(SubjectCreditCategory).where(SubjectCreditCategory.category_id == cat_id))
            for sid, credits in sub_map.items():
                session.add(SubjectCreditCategory(subject_id=sid, category_id=cat_id, credits=credits))
        await session.commit()
    print(f"\nsubject_credit_categories へ {total}件投入しました")


